-- Sakura Cosmetics storefront v2 migration
-- Run once in Supabase SQL Editor before enabling the new storefront.
-- Existing products, variants, orders and order_items are preserved.

alter table public.products
  add column if not exists category text not null default 'full'
    check (category in ('mini', 'full'));

alter table public.product_variants
  add column if not exists stock integer not null default 0
    check (stock >= 0);

create table if not exists public.routine_banners (
  id bigint generated by default as identity primary key,
  title text not null default '',
  image_url text not null,
  sort_order integer not null default 0,
  active boolean not null default true,
  created_at timestamptz not null default now()
);

alter table public.routine_banners enable row level security;

-- Storefront visitors can only read active routine banners.
drop policy if exists "Public can read active routine banners" on public.routine_banners;
create policy "Public can read active routine banners"
  on public.routine_banners for select
  to anon, authenticated
  using (active = true);

-- Only the Sakura admin account can manage routine banners.
drop policy if exists "Sakura admin manages routine banners" on public.routine_banners;
create policy "Sakura admin manages routine banners"
  on public.routine_banners for all
  to authenticated
  using (auth.uid() = 'd0d99fb5-37ab-4daa-8049-198996b326e0'::uuid)
  with check (auth.uid() = 'd0d99fb5-37ab-4daa-8049-198996b326e0'::uuid);


-- Public catalog reads: only active products and variants are visible.
drop policy if exists "Public reads active Sakura products" on public.products;
create policy "Public reads active Sakura products"
  on public.products for select
  to anon, authenticated
  using (active = true);

drop policy if exists "Public reads active Sakura variants" on public.product_variants;
create policy "Public reads active Sakura variants"
  on public.product_variants for select
  to anon, authenticated
  using (active = true);

-- Sakura admin can edit catalog fields and variant stock/prices.
drop policy if exists "Sakura admin manages products" on public.products;
create policy "Sakura admin manages products"
  on public.products for all
  to authenticated
  using (auth.uid() = 'd0d99fb5-37ab-4daa-8049-198996b326e0'::uuid)
  with check (auth.uid() = 'd0d99fb5-37ab-4daa-8049-198996b326e0'::uuid);

drop policy if exists "Sakura admin manages variants" on public.product_variants;
create policy "Sakura admin manages variants"
  on public.product_variants for all
  to authenticated
  using (auth.uid() = 'd0d99fb5-37ab-4daa-8049-198996b326e0'::uuid)
  with check (auth.uid() = 'd0d99fb5-37ab-4daa-8049-198996b326e0'::uuid);

